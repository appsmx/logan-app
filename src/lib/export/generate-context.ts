async function generateDataModelSection(): Promise<string> {
  return `## Modelo de datos

El esquema de Prisma está en \`prisma/schema.prisma\` en el repositorio.
Modelos principales:

- **Project** — nombre, visión, usuarios, estado, fase, modo, repo, llmModel
- **Decision** — DEC-XXX, roleId, problema, alternativas, decisión, justificación
- **Hypothesis** — roleId, contexto, hipótesis, predicción, status, outcome
- **BacklogItem** — título, descripción, status, prioridad
- **SessionContext** — estado, avance, decisiones, pendientes, riesgos
- **PhaseProgress** — fase (1-8), status, notas
- **Audit** — deliverableName, checks (7 items), passed, notes
- **Discovery** — tipo, pregunta, respuesta, clasificación
- **MarketingAsset** — type, title, content, hypothesisId
- **GitAction** — tool, repo, branch, path, commitMessage, prNumber
- **LlmUsage** — projectId, task, provider, model, tokens (tracking)

> Ver \`prisma/schema.prisma\` en el repo para el esquema completo y actualizado.`;
}

function generateDecisionsSection(project: any): string {
  if (project.decisions.length === 0) {
    return `## Decisiones técnicas (DEC-XXX)

Sin decisiones registradas todavía.`;
  }

  const lines = [`## Decisiones técnicas (DEC-XXX)`, ""];
  for (const dec of project.decisions) {
    lines.push(`### ${dec.decId}: ${dec.title}`);
    lines.push(`- **Estado:** ${dec.status}`);
    lines.push(`- **Rol:** ${dec.roleId}`);
    lines.push(`- **Problema:** ${dec.problem}`);
    lines.push(`- **Decisión:** ${dec.decision}`);
    lines.push(`- **Justificación:** ${dec.justification}`);
    lines.push(`- **Fecha:** ${dec.date.toISOString().split("T")[0]}`);
    lines.push("");
  }
  return lines.join("\n");
}

function generateStatusSection(project: any): string {
  const phaseNames: Record<number, string> = {
    1: "Comprender el problema",
    2: "Descubrir información faltante",
    3: "Diseñar la arquitectura",
    4: "Documentar decisiones",
    5: "Construir",
    6: "Auditar",
    7: "Aprender",
    8: "Actualizar documentos",
  };

  return `## Estado actual del proyecto

| Atributo | Valor |
|---|---|
| Estado | ${project.status} |
| Fase actual | ${project.currentPhase}/8 — ${phaseNames[project.currentPhase] || "?"} |
| Modo de trabajo | ${project.currentMode} |
| Decisiones registradas | ${project._count.decisions} |
| Hipótesis registradas | ${project._count.hypotheses} |
| Session contexts | ${project._count.sessionContexts} |
| Repositorio | ${project.repo || "(no configurado)"} |
| Modelo LLM | ${project.llmModel || "(default)"} |

### Hipótesis recientes
${project.hypotheses.slice(0, 5).map((h: any) => 
  `- **[${h.status}]** ${h.roleId}: ${h.hypothesis.substring(0, 100)}...`
).join("\n") || "Sin hipótesis registradas."}`;
}

