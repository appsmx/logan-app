export interface ExportContextRequest {
  projectId: string;
  includeSource?: boolean; // if true, also generate tar.gz
}

export interface ExportContextResult {
  contextMarkdown: string;
  sourceSize?: number;
  fileCount: number;
  contextSize: number;
}

export async function generateContextExport(
  req: ExportContextRequest,
): Promise<ExportContextResult> {
  const project = await db.project.findUnique({
    where: { id: req.projectId },
    include: {
      decisions: { orderBy: { date: "desc" }, take: 20 },
      hypotheses: { orderBy: { createdAt: "desc" }, take: 20 },
      _count: { select: { decisions: true, hypotheses: true, sessionContexts: true } },
    },
  });

  if (!project) {
    throw new Error("Proyecto no encontrado");
  }

  const sections: string[] = [];

  // 1. Header
  sections.push(generateHeader(project));

  // 2. Resumen ejecutivo
  sections.push(generateExecutiveSummary(project));

  // 3. Stack tecnológico
  sections.push(generateStackSection(project));

  // 4. Modelo de datos
  sections.push(await generateDataModelSection());

  // 5. Decisiones técnicas
  sections.push(generateDecisionsSection(project));

  // 6. Estado actual
  sections.push(generateStatusSection(project));

  // 7. Archivos clave (embebidos)
  // Note: in production (Vercel), we can't read the filesystem.
  // This section is generated by the client or by LOGAN reading the repo via GitHub API.
  sections.push(generateFilesNote(project));

  // 8. Cómo probar localmente
  sections.push(generateLocalSetupSection(project));

  const contextMarkdown = sections.join("\n\n---\n\n");

  return {
    contextMarkdown,
    fileCount: project.decisions.length,
    contextSize: contextMarkdown.length,
  };
}

function generateHeader(project: any): string {
  const date = new Date().toISOString().split("T")[0];
  return `# ${project.name} — Contexto para IA

**Fecha de exportación:** ${date}
**Generado por:** LOGAN OS (DEC-LOGAN-017)
**Proyecto:** ${project.name}
**ID:** ${project.id}
**Repositorio:** ${project.repo || "(no configurado)"}

> Este documento es un contexto curado para que cualquier IA pueda entender
> el proyecto sin necesidad de explorar el código desde cero.
> Generado bajo LOGAN Art. I (conocimiento como activo estratégico).`;
}

function generateExecutiveSummary(project: any): string {
  return `## Resumen ejecutivo

**Visión:** ${project.vision}

**Usuarios objetivo:**
${parseUsers(project.users).map((u: string) => `- ${u}`).join("\n")}

**Estado:** ${project.status} | **Fase:** ${project.currentPhase}/8 | **Modo:** ${project.currentMode}`;
}

